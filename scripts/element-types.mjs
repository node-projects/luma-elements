import {readdir,readFile,writeFile} from 'node:fs/promises';
const entries=[];
for(const name of (await readdir('src')).filter(n=>n.endsWith('.ts')&&n!=='elements.ts')){
 const source=await readFile('src/'+name,'utf8');
 for(const match of source.matchAll(/register\('([a-z-]+)',\s*([A-Za-z0-9_]+)/g))entries.push(`    '${match[1]}': import('./${name.replace(/\.ts$/,'.js')}').${match[2]};`);
}
await writeFile('src/elements.ts','// Generated by scripts/element-types.mjs from actual tag registrations.\nexport {};\ndeclare global {\n  interface HTMLElementTagNameMap {\n'+entries.sort().join('\n')+'\n  }\n}\n');
